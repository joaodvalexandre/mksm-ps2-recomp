#!/usr/bin/env python3
"""Generates the port status map (SVG treemap) and its details table.

Inputs:   docs/status/data.toml, config/funcmap.csv
Outputs:  docs/status/map.svg, docs/status/details.md

Usage:  python tools/status/generate.py          (regenerates the files)
        python tools/status/generate.py --check  (fails if the files are not up to date)

Uses only the standard library (Python 3.11+ for tomllib).
"""
from __future__ import annotations

import argparse
import bisect
import csv
import math
import sys
import tomllib
from dataclasses import dataclass
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "docs" / "status" / "data.toml"
FUNCMAP = ROOT / "config" / "funcmap.csv"
OUTPUT = ROOT / "docs" / "status"

STATUSES = ("ok", "partial", "pending")

TEXT = {
    "title": "Status",
    "libraries": "libraries*",
    "hardware": "hardware",
    "panel_lib": "Sony SDK libraries*",
    "panel_hw": "PS2 hardware",
    "ok": "Working",
    "partial": "Partial",
    "pending": "Pending",
    "footer": "* Functions of the static Sony libraries linked into the game ELF (config/funcmap.csv). "
              "Hardware: weighted per component.",
    "details_title": "Port status: details",
    "details_intro": "Generated by `tools/status/generate.py` from `docs/status/data.toml` and "
                     "`config/funcmap.csv`. Do not edit by hand.",
    "col_lib": "Library", "col_func": "Functions", "col_status": "Status", "col_note": "Note",
    "col_comp": "Component", "col_group": "Group", "col_weight": "Weight",
    "total": "Total",
}

ICON = {"ok": "✅", "partial": "🔧", "pending": "⏳"}

# ---------------------------------------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------------------------------------


@dataclass
class Cell:
    label: str   # tooltip text
    status: str


@dataclass
class Group:
    name: str            # label drawn over the group
    cells: list[Cell]
    weights: list[float]  # relative size of each cell
    label_cells: bool     # draw the label of each cell (hardware panel)
    shorts: list[str]


def check_status(status: str, where: str) -> str:
    if status not in STATUSES:
        sys.exit(f"data.toml: unknown status '{status}' in {where} (use {', '.join(STATUSES)})")
    return status


def load_functions() -> list[tuple[int, int]]:
    with FUNCMAP.open(newline="", encoding="utf-8") as f:
        return sorted((int(r["Start"], 16), int(r["Size"])) for r in csv.DictReader(f))


def libraries(data: dict) -> tuple[list[Group], list[dict]]:
    lib = data["libraries"]
    entries = sorted(lib["group"], key=lambda g: g["start"])
    starts = [g["start"] for g in entries]
    if starts[0] > lib["from"]:
        sys.exit("data.toml: the first library must start at `from` or earlier")
    by_name: dict[str, list[tuple[int, int]]] = {}
    order: list[str] = []
    for address, size in load_functions():
        if not lib["from"] <= address < lib["to"]:
            continue
        g = entries[bisect.bisect_right(starts, address) - 1]
        if g.get("skip"):  # game code between two runs of linked libraries
            continue
        if g["name"] not in by_name:
            by_name[g["name"]] = []
            order.append(g["name"])
        by_name[g["name"]].append((address, size))

    info = {}
    for g in entries:
        if g.get("skip"):
            continue
        status = check_status(g["status"], g["name"])
        previous = info.get(g["name"])
        if previous and previous["status"] != status:
            sys.exit(f"data.toml: '{g['name']}' appears with different statuses")
        info[g["name"]] = {"status": status, "note": g.get("note") or (previous or {}).get("note", "")}

    groups, rows = [], []
    for name in order:
        funcs = by_name[name]
        status = info[name]["status"]
        cells = [Cell(f"{name} · sub_{d:08X} ({s} B)", status) for d, s in funcs]
        groups.append(Group(name, cells, [1.0] * len(cells), False, []))
        rows.append({"name": name, "n": len(funcs), "status": status, "note": info[name]["note"],
                     "from": funcs[0][0], "to": funcs[-1][0] + funcs[-1][1]})
    return groups, rows


def hardware(data: dict) -> tuple[list[Group], list[dict]]:
    groups, rows = [], []
    for g in data["hardware"]["group"]:
        cells, weights, shorts = [], [], []
        for c in g["component"]:
            status = check_status(c["status"], c["short"])
            name = c["name"]
            note = c.get("note", "")
            cells.append(Cell(name + (f" — {note}" if note else ""), status))
            weights.append(float(c.get("weight", 1)))
            shorts.append(c["short"])
            rows.append({"group": g["name"], "name": name, "status": status, "note": note,
                         "weight": c.get("weight", 1)})
        groups.append(Group(g["name"], cells, weights, True, shorts))
    return groups, rows


def percentage(groups: list[Group]) -> tuple[float, float, float]:
    """(percentage that works, weight that works, total weight)."""
    ok = total = 0.0
    for g in groups:
        for c, w in zip(g.cells, g.weights):
            total += w
            ok += w if c.status == "ok" else 0.0
    return (100.0 * ok / total if total else 0.0), ok, total


# ---------------------------------------------------------------------------------------------------------
# Treemap ("squarified" algorithm by Bruls, Huizing and van Wijk)
# ---------------------------------------------------------------------------------------------------------

Rect = tuple[float, float, float, float]


def squarify(values: list[float], x: float, y: float, w: float, h: float) -> list[Rect]:
    """Rectangles (in the order of `values`, which must go from largest to smallest) that fill x,y,w,h."""
    total = sum(values)
    if total <= 0 or not values:
        return [(x, y, 0.0, 0.0)] * len(values)
    areas = [v * w * h / total for v in values]
    rects: list[Rect] = []
    i = 0
    while i < len(areas):
        side = min(w, h)
        row = [areas[i]]
        j = i + 1

        def worst(r: list[float]) -> float:
            s = sum(r)
            return max(max(side * side * a / (s * s), (s * s) / (side * side * a)) for a in r)

        while j < len(areas) and worst(row + [areas[j]]) <= worst(row):
            row.append(areas[j])
            j += 1
        s = sum(row)
        if w >= h:   # column on the left
            width = s / h
            yy = y
            for a in row:
                rects.append((x, yy, width, a / width))
                yy += a / width
            x, w = x + width, w - width
        else:        # row on top
            height = s / w
            xx = x
            for a in row:
                rects.append((xx, y, a / height, height))
                xx += a / height
            y, h = y + height, h - height
        i = j
    return rects


def grid(n: int, w: float, h: float) -> tuple[int, int]:
    """Columns and rows for n equal cells as square as possible in w x h."""
    best = (1, n)
    best_cost = math.inf
    for cols in range(1, n + 1):
        rows = math.ceil(n / cols)
        cw, ch = w / cols, h / rows
        cost = max(cw / ch, ch / cw) + 0.02 * (cols * rows - n)
        if cost < best_cost:
            best, best_cost = (cols, rows), cost
    return best


# ---------------------------------------------------------------------------------------------------------
# SVG
# ---------------------------------------------------------------------------------------------------------

WIDTH = 900
MARGIN = 16
PANEL_GAP = 20
MAP_HEIGHT = 260
GROUP_GAP = 2.0
CELL_GAP = 1.0

STYLE = """
  .background { fill: #ffffff; }
  .border { stroke: #d0d7de; }
  .t1 { fill: #1f2328; }
  .t2 { fill: #59636e; }
  .ok { fill: #0ca30c; }
  .partial { fill: #fab219; }
  .pending { fill: #c4c8ce; }
  .hatch { stroke: #8a5a00; }
  .chip { fill: #ffffff; fill-opacity: .85; }
  .badge-k { fill: #59636e; }
  .badge-t { fill: #ffffff; }
  .badge-v-dark { fill: #1f2328; }
  .text-pending { fill: #1f2328; }
  .group { fill: #ffffff; }
  @media (prefers-color-scheme: dark) {
    .background { fill: #0d1117; }
    .border { stroke: #30363d; }
    .t1 { fill: #e6edf3; }
    .t2 { fill: #9198a1; }
    .pending { fill: #4b525c; }
    .chip { fill: #0d1117; fill-opacity: .8; }
    .badge-k { fill: #3d444d; }
    .text-pending { fill: #e6edf3; }
    .group { fill: #0d1117; }
  }
"""

FONT = "font-family=\"-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif\""


def text_width(s: str, size: float) -> float:
    return len(s) * size * 0.6


def num(v: float) -> str:
    return f"{v:.1f}".rstrip("0").rstrip(".")


def fmt_pct(p: float) -> str:
    return f"{p:.1f}%"


def badge_class(p: float) -> str:
    return "ok" if p >= 75 else ("partial" if p >= 40 else "pending")


def badge(x: float, y: float, key: str, value: str, cls: str) -> tuple[list[str], float]:
    size, height, pad = 12, 22, 8
    wk = text_width(key, size) + 2 * pad
    wv = text_width(value, size) + 2 * pad
    value_text = "badge-v-dark" if cls == "partial" else "badge-t"
    parts = [
        f'<rect class="badge-k" x="{num(x)}" y="{num(y)}" width="{num(wk)}" height="{height}" rx="3"/>',
        f'<rect class="{cls}" x="{num(x + wk)}" y="{num(y)}" width="{num(wv)}" height="{height}" rx="3"/>',
        f'<rect class="{cls}" x="{num(x + wk)}" y="{num(y)}" width="4" height="{height}"/>',
        f'<text class="badge-t" x="{num(x + wk / 2)}" y="{num(y + 15)}" font-size="{size}" text-anchor="middle">{escape(key)}</text>',
        f'<text class="{value_text}" x="{num(x + wk + wv / 2)}" y="{num(y + 15)}" font-size="{size}" '
        f'font-weight="600" text-anchor="middle">{escape(value)}</text>',
    ]
    return parts, wk + wv


def draw_panel(groups: list[Group], x: float, y: float, w: float, h: float) -> list[str]:
    out = [f'<rect class="group" x="{num(x)}" y="{num(y)}" width="{num(w)}" height="{num(h)}"/>']
    groups = sorted(groups, key=lambda g: -sum(g.weights))
    rects = squarify([sum(g.weights) for g in groups], x, y, w, h)
    labels: list[str] = []
    for g, (gx, gy, gw, gh) in zip(groups, rects):
        gx, gy = gx + GROUP_GAP / 2, gy + GROUP_GAP / 2
        gw, gh = gw - GROUP_GAP, gh - GROUP_GAP
        if gw <= 0 or gh <= 0:
            continue
        order = sorted(range(len(g.cells)), key=lambda i: (STATUSES.index(g.cells[i].status), -g.weights[i]))
        if g.label_cells:
            sub = squarify([g.weights[i] for i in order], gx, gy, gw, gh)
        else:
            cols, rows = grid(len(order), gw, gh)
            cw, ch = gw / cols, gh / rows
            sub = [(gx + (k % cols) * cw, gy + (k // cols) * ch, cw, ch) for k in range(len(order))]
        for i, (cx, cy, cw, ch) in zip(order, sub):
            c = g.cells[i]
            rx, ry = cx + CELL_GAP / 2, cy + CELL_GAP / 2
            rw, rh = max(cw - CELL_GAP, 0.5), max(ch - CELL_GAP, 0.5)
            fill = ' fill="url(#hatch)"' if c.status == "partial" else ""
            out.append(f'<rect class="{c.status}" x="{num(rx)}" y="{num(ry)}" width="{num(rw)}" '
                       f'height="{num(rh)}"><title>{escape(c.label)}</title></rect>')
            if fill:
                out.append(f'<rect x="{num(rx)}" y="{num(ry)}" width="{num(rw)}" height="{num(rh)}"'
                           f'{fill} pointer-events="none"/>')
            if g.label_cells:
                short = g.shorts[i]
                size = next((t for t in (11, 9) if text_width(short, t) + 6 <= rw and rh >= t + 5), None)
                # If it does not fit horizontally, try vertically (tall, narrow cells)
                vertical = False
                if size is None:
                    size = next((t for t in (11, 9) if text_width(short, t) + 6 <= rh and rw >= t + 5), None)
                    vertical = size is not None
                if size:
                    color = {"ok": "badge-t", "partial": "badge-v-dark", "pending": "text-pending"}[c.status]
                    tx, ty = rx + rw / 2, ry + rh / 2
                    rotation = f' transform="rotate(-90 {num(tx)} {num(ty)})"' if vertical else ""
                    out.append(f'<text class="{color}" x="{num(tx)}" y="{num(ty + size * 0.35)}" '
                               f'font-size="{size}" text-anchor="middle"{rotation} pointer-events="none">{escape(short)}</text>')
        size = 11
        chip_width = text_width(g.name, size) + 8
        if chip_width <= gw and gh >= 16:
            labels.append(f'<rect class="chip" x="{num(gx + 1)}" y="{num(gy + 1)}" width="{num(chip_width)}" '
                          f'height="15" rx="2" pointer-events="none"/>')
            labels.append(f'<text class="t1" x="{num(gx + 5)}" y="{num(gy + 12)}" font-size="{size}" '
                          f'pointer-events="none">{escape(g.name)}</text>')
    return out + labels


def svg(lib: list[Group], hw: list[Group]) -> str:
    t = TEXT
    p_lib, ok_lib, tot_lib = percentage(lib)
    p_hw, _, _ = percentage(hw)
    panel_width = (WIDTH - 2 * MARGIN - PANEL_GAP) / 2
    y_badges = 56
    y_panels = y_badges + 46
    y_map = y_panels + 10
    y_legend = y_map + MAP_HEIGHT + 22
    height = y_legend + 30

    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" viewBox="0 0 {WIDTH} {height}" '
         f'{FONT} role="img" aria-labelledby="status-title">',
         f'<title id="status-title">{escape(t["title"])}: {escape(t["libraries"])} {fmt_pct(p_lib)}, '
         f'{escape(t["hardware"])} {fmt_pct(p_hw)}</title>',
         f"<style>{STYLE}</style>",
         '<defs><pattern id="hatch" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
         '<line class="hatch" x1="0" y1="0" x2="0" y2="6" stroke-width="1.5" stroke-opacity=".55"/></pattern></defs>',
         f'<rect class="background" width="{WIDTH}" height="{height}" rx="6"/>',
         f'<text class="t1" x="{MARGIN}" y="34" font-size="24" font-weight="600">{escape(t["title"])}</text>',
         f'<line class="border" x1="{MARGIN}" y1="44" x2="{WIDTH - MARGIN}" y2="44" stroke-width="1"/>']
    x = MARGIN
    for key, p in ((t["libraries"], p_lib), (t["hardware"], p_hw)):
        parts, width = badge(x, y_badges, key, fmt_pct(p), badge_class(p))
        o += parts
        x += width + 8

    for i, (title, groups, extra) in enumerate((
            (t["panel_lib"], lib, f" ({int(ok_lib)}/{int(tot_lib)})"),
            (t["panel_hw"], hw, ""))):
        px = MARGIN + i * (panel_width + PANEL_GAP)
        p, _, _ = percentage(groups)
        o.append(f'<text class="t1" x="{num(px)}" y="{y_panels}" font-size="14">'
                 f'{escape(title)}: {fmt_pct(p)}{extra}</text>')
        o += draw_panel(groups, px, y_map, panel_width, MAP_HEIGHT)

    # Legend (the status never depends on color alone: partial is hatched and everything has text)
    x = MARGIN
    for status in STATUSES:
        o.append(f'<rect class="{status}" x="{x}" y="{y_legend - 10}" width="12" height="12" rx="2"/>')
        if status == "partial":
            o.append(f'<rect x="{x}" y="{y_legend - 10}" width="12" height="12" rx="2" fill="url(#hatch)"/>')
        o.append(f'<text class="t2" x="{x + 17}" y="{y_legend}" font-size="12">{escape(t[status])}</text>')
        x += 17 + text_width(t[status], 12) + 18
    o.append(f'<text class="t2" x="{MARGIN}" y="{y_legend + 20}" font-size="11">{escape(t["footer"])}</text>')
    o.append("</svg>")
    return "\n".join(o) + "\n"


# ---------------------------------------------------------------------------------------------------------
# Details table (the same information as text, for screen readers and for searching)
# ---------------------------------------------------------------------------------------------------------


def markdown(lib: list[Group], lib_rows: list[dict], hw: list[Group], hw_rows: list[dict]) -> str:
    t = TEXT
    p_lib, ok_lib, tot_lib = percentage(lib)
    p_hw, _, _ = percentage(hw)
    status = lambda s: f"{ICON[s]} {t[s]}"
    o = [f"# {t['details_title']}", "", f"![{t['title']}](map.svg)", "", t["details_intro"], "",
         f"## {t['panel_lib']}: {fmt_pct(p_lib)} ({int(ok_lib)}/{int(tot_lib)})", "",
         f"| {t['col_lib']} | {t['col_func']} | {t['col_status']} | {t['col_note']} |", "|---|---:|---|---|"]
    for r in sorted(lib_rows, key=lambda r: r["from"]):
        o.append(f"| `{r['name']}` | {r['n']} | {status(r['status'])} | {r['note']} |")
    o += ["", f"## {t['panel_hw']}: {fmt_pct(p_hw)}", "",
          f"| {t['col_group']} | {t['col_comp']} | {t['col_weight']} | {t['col_status']} | {t['col_note']} |",
          "|---|---|---:|---|---|"]
    for r in hw_rows:
        o.append(f"| {r['group']} | {r['name']} | {r['weight']} | {status(r['status'])} | {r['note']} |")
    o += ["", t["footer"], ""]
    return "\n".join(o)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="does not write; fails if any file is not up to date")
    args = ap.parse_args()

    with DATA.open("rb") as f:
        data = tomllib.load(f)

    lib, lib_rows = libraries(data)
    hw, hw_rows = hardware(data)
    expected: dict[Path, str] = {
        OUTPUT / "map.svg": svg(lib, hw),
        OUTPUT / "details.md": markdown(lib, lib_rows, hw, hw_rows),
    }

    outdated = [p for p, c in expected.items()
                if not p.exists() or p.read_text(encoding="utf-8") != c]
    if args.check:
        for p in outdated:
            print(f"out of date: {p.relative_to(ROOT).as_posix()}")
        if outdated:
            print("Run: python tools/status/generate.py")
        return 1 if outdated else 0
    for p in outdated:
        p.write_text(expected[p], encoding="utf-8", newline="\n")
        print(f"written: {p.relative_to(ROOT).as_posix()}")
    if not outdated:
        print("no changes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
